//! Text generation: sampling the next byte from the model, one token at a time.
//!
//! Every new token needs a full forward pass over the context window (there is no key/value
//! cache yet), so generation costs roughly `window × params × 2` FLOPs per token. A 128-token
//! window keeps this fast enough for the small models GERMEN targets.

use crate::data::Rng;
use crate::model::Gpt;
use burn::prelude::*;

/// Sampling settings.
#[derive(Clone, Debug)]
pub struct SampleOptions {
    /// Number of new tokens (bytes) to produce.
    pub max_new: usize,
    /// Softmax temperature. `0` (or less) means greedy decoding; higher means more random.
    pub temperature: f32,
    /// Only the `top_k` most likely tokens are considered; `0` disables the filter.
    pub top_k: usize,
    /// At most this many of the most recent tokens are fed to the model per step.
    pub window: usize,
}

impl Default for SampleOptions {
    fn default() -> Self {
        SampleOptions {
            max_new: 200,
            temperature: 0.8,
            top_k: 40,
            window: 128,
        }
    }
}

/// Chooses a token from raw `logits`.
///
/// Greedy when `temperature <= 0` or `top_k == 1`; otherwise samples from the softmax of
/// `logits / temperature` restricted to the `top_k` highest logits.
pub fn sample_logits(logits: &[f32], temperature: f32, top_k: usize, rng: &mut Rng) -> u8 {
    assert!(
        !logits.is_empty() && logits.len() <= 256,
        "expected 1..=256 logits"
    );

    let argmax = || {
        let mut best = 0;
        for (i, &l) in logits.iter().enumerate() {
            if l > logits[best] {
                best = i;
            }
        }
        best as u8
    };
    if temperature <= 0.0 || top_k == 1 {
        return argmax();
    }

    let mut order: Vec<usize> = (0..logits.len()).collect();
    order.sort_by(|&a, &b| logits[b].total_cmp(&logits[a]));
    if top_k > 0 && top_k < order.len() {
        order.truncate(top_k);
    }

    let max = logits[order[0]];
    let weights: Vec<f32> = order
        .iter()
        .map(|&i| ((logits[i] - max) / temperature).exp())
        .collect();
    let total: f32 = weights.iter().sum();
    if !total.is_finite() || total <= 0.0 {
        return argmax();
    }
    let mut draw = rng.next_f32() * total;
    for (k, w) in weights.iter().enumerate() {
        draw -= w;
        if draw <= 0.0 {
            return order[k] as u8;
        }
    }
    order[order.len() - 1] as u8
}

/// Continues `prompt` by `opts.max_new` tokens. `on_token` is called with each new byte as soon
/// as it is chosen (use it to stream the text). An empty prompt starts from a newline.
///
/// Returns only the newly generated bytes.
pub fn generate(
    model: &Gpt,
    prompt: &[u8],
    opts: &SampleOptions,
    rng: &mut Rng,
    device: &Device,
    mut on_token: impl FnMut(u8),
) -> Vec<u8> {
    let mut context: Vec<u8> = if prompt.is_empty() {
        vec![b'\n']
    } else {
        prompt.to_vec()
    };
    let window = opts.window.clamp(1, model.block_size());
    let mut out = Vec::with_capacity(opts.max_new);

    for _ in 0..opts.max_new {
        let start = context.len().saturating_sub(window);
        let slice = &context[start..];
        let t = slice.len();
        let ids: Vec<i32> = slice.iter().map(|&b| b as i32).collect();
        let x = Tensor::<2, Int>::from_data(TensorData::new(ids, [1, t]), device);

        let logits = model.forward(x); // [1, t, vocab]
        let vocab = logits.dims()[2];
        let last = logits.slice([0..1, t - 1..t, 0..vocab]).reshape([vocab]);
        let values: Vec<f32> = last
            .into_data()
            .try_to_vec::<f32>()
            .expect("logits are f32");

        let next = sample_logits(&values, opts.temperature, opts.top_k, rng);
        context.push(next);
        out.push(next);
        on_token(next);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Preset;

    #[test]
    fn greedy_and_top1_pick_the_largest_logit() {
        let mut rng = Rng::new(1);
        let logits = [0.1, 2.5, -1.0, 2.4];
        assert_eq!(sample_logits(&logits, 0.0, 0, &mut rng), 1);
        assert_eq!(sample_logits(&logits, 1.0, 1, &mut rng), 1);
    }

    #[test]
    fn sampling_follows_the_distribution() {
        let mut rng = Rng::new(5);
        // Strongly peaked: index 0 should win almost always.
        let peaked = [10.0, 0.0, 0.0];
        let wins = (0..300)
            .filter(|_| sample_logits(&peaked, 1.0, 0, &mut rng) == 0)
            .count();
        assert!(wins > 290, "wins = {wins}");
        // Uniform: every index should appear.
        let flat = [0.0; 4];
        let mut seen = [false; 4];
        for _ in 0..200 {
            seen[sample_logits(&flat, 1.0, 0, &mut rng) as usize] = true;
        }
        assert!(seen.iter().all(|&s| s));
    }

    #[test]
    fn top_k_excludes_unlikely_tokens() {
        let mut rng = Rng::new(9);
        let logits = [5.0, 4.9, -3.0, -3.0, -3.0];
        for _ in 0..300 {
            let t = sample_logits(&logits, 2.0, 2, &mut rng);
            assert!(t < 2, "token {t} is outside the top 2");
        }
    }

    #[test]
    fn generate_returns_requested_length_and_streams_tokens() {
        let device = Device::flex();
        let model = Preset::Nano.config(16).init(&device);
        let opts = SampleOptions {
            max_new: 12,
            temperature: 1.0,
            top_k: 0,
            window: 8,
        };
        let mut rng = Rng::new(3);
        let mut streamed = Vec::new();
        let out = generate(
            &model,
            b"Ana citeste o carte veche",
            &opts,
            &mut rng,
            &device,
            |b| streamed.push(b),
        );
        assert_eq!(out.len(), 12);
        assert_eq!(out, streamed);
    }

    #[test]
    fn generate_is_deterministic_for_a_fixed_seed() {
        let device = Device::flex();
        let model = Preset::Nano.config(16).init(&device);
        let opts = SampleOptions {
            max_new: 8,
            ..SampleOptions::default()
        };
        let a = generate(&model, b"", &opts, &mut Rng::new(42), &device, |_| {});
        let b = generate(&model, b"", &opts, &mut Rng::new(42), &device, |_| {});
        assert_eq!(a, b);
    }
}
